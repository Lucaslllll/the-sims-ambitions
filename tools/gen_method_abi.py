#!/usr/bin/env python3
"""Generate typed ARM ABI registrations from the existing ObjC method tables."""
from pathlib import Path
import re
import sys

source, output = map(Path, sys.argv[1:3])
output.mkdir(parents=True, exist_ok=True)
for path in (source / "hle").glob("*.cpp"):
    names = sorted(set(re.findall(
        r"\badd_(?:class_)?method\s*\([^;]+?\(void\*\)\s*(\w+)\s*\)",
        path.read_text())))
    text = "// Generated by tools/gen_method_abi.py.\n#if defined(__arm__)\n"
    for name in names:
        text += f"abi::register_method((void*){name}, abi::signature_of({name}));\n"
    text += "#endif\n"
    dest = output / (path.stem + "_abi.inc")
    if not dest.exists() or dest.read_text() != text:
        dest.write_text(text)
